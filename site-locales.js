function localizeCourse(locale) {
  const isEnglish = locale === "en";
  const localizedLessons = isEnglish ? lessons.map((lesson) => {
    const { points, ...copy } = englishLessons[lesson.id];
    return {
      ...lesson,
      ...copy,
      title: lesson.en,
      points: points.map((point, index) => [...point, lesson.points[index][2]]),
    };
  }) : lessons;
  const localizedTranscripts = isEnglish ? transcripts.map((item) => {
    const [title, note] = englishTranscripts[item.id];
    return { ...item, title, note };
  }) : transcripts;
  const localizedSources = isEnglish ? sourceArchive.map(([, file]) => {
    if (file in englishSources) {
      const [title, note] = englishSources[file];
      return [title, file, note];
    }
    const classNumber = file.slice(5, 7);
    return [`Class ${classNumber} data`, file, localizedLessons[Number(classNumber) - 1].title];
  }) : sourceArchive;
  const localizedSamples = isEnglish ? samples.map((question) => {
    const { fieldLabels, rowLabels, ...copy } = englishSamples[question.id];
    return {
      ...question,
      ...copy,
      rows: question.rows?.map(([, ...values], index) => [rowLabels[index], ...values]),
      fields: question.fields?.map((field, index) => ({ ...field, label: fieldLabels[index] })),
    };
  }) : samples;
  const localizedSlides = slideQuestions.map((question) => {
    const { discussionPrompt, discussionAnswer, ...copy } = slideLocales[question.id][locale];
    const translated = { ...question, ...copy, title: isEnglish ? question.originalTitle : question.title };
    if (question.discussion) {
      translated.discussion = {
        prompt: discussionPrompt ?? question.discussion.prompt,
        answer: discussionAnswer ?? question.discussion.answer,
      };
    }
    return translated;
  });

  return {
    lessons: localizedLessons,
    transcripts: localizedTranscripts,
    sourceArchive: localizedSources,
    samples: localizedSamples,
    slideQuestions: localizedSlides,
    questions: [...localizedSamples, ...localizedSlides],
  };
}
